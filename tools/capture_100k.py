#!/usr/bin/env python3
"""Capture OVITO CNA ground truth for the 108k-atom differential test.

The 108k fixture itself is *not* committed. The Rust generator in
``crates/rmda-core/tests/cna_scale.rs`` rebuilds the identical atom block at test
time, so only the expected per-atom ``StructureType`` codes are stored. Regenerate
both halves with::

    cargo test -p rmda-core --test cna_scale -- --ignored emit_100k_xyz
    python3 tools/capture_100k.py

The emitter writes to ``target/m2_100k.xyz``; pass a path explicitly to override
the input, and a second argument to override the output.
"""

import os
import sys

import numpy as np
from ovito.io import import_file
from ovito.modifiers import CommonNeighborAnalysisModifier as CNA


def ovito_version():
    """The running OVITO's version, for the generated files' headers."""
    import ovito

    return ".".join(map(str, ovito.version))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CODES = "0=OTHER 1=FCC 2=HCP 3=BCC 4=ICO 5=SC"


def summarise(v):
    u, c = np.unique(v, return_counts=True)
    return ",".join(f"{int(a)}x{int(b)}" for a, b in zip(u, c))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "target", "m2_100k.xyz")
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "tests", "data", "m2_100k_expected.txt")
    if not os.path.exists(src):
        sys.exit(
            f"{src} not found; run "
            "`cargo test -p rmda-core --test cna_scale -- --ignored emit_100k_xyz` first"
        )

    # rmda's default CNA mode is OVITO's adaptive (determineStructureAdaptive).
    pipe = import_file(src)
    pipe.modifiers.append(CNA(mode=CNA.Mode.AdaptiveCutoff))
    types = np.array(pipe.compute().particles["Structure Type"], dtype=np.int64)
    print(f"{src}: natoms={len(types)} cna={summarise(types)}")

    with open(dst, "w") as fh:
        fh.write(f"# generated by tools/capture_100k.py (OVITO {ovito_version()})\n")
        fh.write(f"# codes: {CODES}\n")
        fh.write("# the 108k fixture itself is not committed; the Rust test\n")
        fh.write("# regenerates the identical atom block before comparing.\n")
        fh.write("fixture m2_100k\n")
        fh.write(f"natoms {len(types)}\n")
        fh.write("cna_adaptive " + " ".join(str(int(t)) for t in types) + "\n")
    print("wrote", dst)


if __name__ == "__main__":
    main()
