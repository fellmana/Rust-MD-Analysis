#!/usr/bin/env python3
"""Regenerate `tests/data/ptm_refdata_graphs.txt` from the upstream PTM sources.

The reference-graph table's `hash` and `canonical_labelling` are *derived* at
run time by upstream `ptm_initialize_global`, not stored in its data files:

    for each graph:
        degree      <- graph_degree(num_facets, facets, num_nbrs)
        re-wind     <- add_facet(..., origin) rewrites every facet clockwise
        hash, lab   <- canonical_form_coloured(facets, degree, colours)

`colours` is all zero except for the diamonds, whose four inner neighbours are
coloured 1 (upstream `dcolours`).

Both are load-bearing: `check_graphs` selects candidate reference graphs by
hash, then uses the labelling to build the point mapping. A divergence in either
would silently change which structures match, so the derivation is pinned by a
differential test rather than trusted.

This script compiles the upstream C++ with a small probe that performs exactly
that derivation and prints the result. The Rust port in
`crates/rmda-core/src/analysis/ptm/refdata.rs` is compared against the output by
`crates/rmda-core/tests/ptm_refdata.rs`.

Usage
-----
    python3 tools/gen_ptm_refdata.py --upstream <dir> \
        --out tests/data/ptm_refdata_graphs.txt

`<dir>` must contain the upstream sources: `ptm_graph_data.cpp`,
`ptm_canonical_coloured.cpp`, `ptm_graph_tools.cpp`,
`ptm_convex_hull_incremental.cpp` and their headers, plus `ptm_constants.h` and
`ptm_initialize_data.h`. (Upstream master carries the ideal templates in
`ptm_constants.h`; older/OVITO copies put them in `ptm_templates.h`, which
`--templates-extra` can add to the include path.)
"""

import argparse
import os
import subprocess
import sys
import tempfile

# The probe mirrors the static `initialize_graphs` in
# ptm_initialize_data.cpp verbatim, including the diamonds' `dcolours`.
PROBE = r"""
#include <cstdio>
#include <cstring>
#include "ptm_initialize_data.h"
#include "ptm_graph_data.h"
#include "ptm_canonical_coloured.h"
#include "ptm_graph_tools.h"
#include "ptm_convex_hull_incremental.h"

using namespace ptm;

static void dump(const char* name, const refdata_t* s, bool diamond = false) {
    int8_t colours[PTM_MAX_POINTS] = {0};
    if (diamond)
        for (int k = 0; k < 4; k++) colours[k] = 1;
    for (int i = 0; i < s->num_graphs; i++) {
        int8_t degree[PTM_MAX_NBRS];
        graph_degree(s->num_facets, s->graphs[i].facets, s->num_nbrs, degree);

        double plane_normal[3];
        double origin[3] = {0, 0, 0};
        for (int f = 0; f < s->num_facets; f++)
            add_facet(&s->points[1], s->graphs[i].facets[f][0], s->graphs[i].facets[f][1],
                      s->graphs[i].facets[f][2], s->graphs[i].facets[f], plane_normal, origin);

        int8_t code[2 * PTM_MAX_EDGES];
        int8_t cl[PTM_MAX_POINTS];
        canonical_form_coloured(s->num_facets, s->graphs[i].facets, s->num_nbrs, degree,
                                colours, cl, code, &s->graphs[i].hash);
        printf("%s %d %016llx", name, i, (unsigned long long)s->graphs[i].hash);
        for (int k = 0; k < s->num_nbrs; k++) printf(" %d", cl[k]);
        printf("\n");
    }
}

int main() {
    dump("sc",  &structure_sc);
    dump("fcc", &structure_fcc);
    dump("hcp", &structure_hcp);
    dump("ico", &structure_ico);
    dump("bcc", &structure_bcc);
    dump("dcub", &structure_dcub, true);
    dump("dhex", &structure_dhex, true);
    return 0;
}
"""

SOURCES = [
    "ptm_graph_data.cpp",
    "ptm_canonical_coloured.cpp",
    "ptm_graph_tools.cpp",
    "ptm_convex_hull_incremental.cpp",
]

HEADER = """# Reference-graph table derived by upstream PTM, used by
# crates/rmda-core/tests/ptm_refdata.rs.
#
# One row per in-scope reference graph: "<structure> <index> <hash> <labelling...>"
# where <hash> is the canonical-form hash and <labelling> the 1-based canonical
# label of each neighbour.
#
# GENERATED by tools/gen_ptm_refdata.py. Do not edit by hand.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--upstream", required=True, help="directory of upstream PTM sources")
    ap.add_argument("--out", required=True)
    ap.add_argument(
        "--templates-extra",
        help="extra include dir, for older copies where ptm_templates.h is separate",
    )
    args = ap.parse_args()

    upstream = os.path.abspath(args.upstream)
    missing = [s for s in SOURCES if not os.path.exists(os.path.join(upstream, s))]
    if missing:
        sys.exit("missing upstream sources in %s: %s" % (upstream, ", ".join(missing)))

    with tempfile.TemporaryDirectory() as td:
        probe_cpp = os.path.join(td, "probe.cpp")
        with open(probe_cpp, "w") as f:
            f.write(PROBE)
        binary = os.path.join(td, "probe")

        cmd = [
            "g++", "-O0", "-std=c++11",
            "-I", upstream,
            "-o", binary,
            probe_cpp,
        ] + [os.path.join(upstream, s) for s in SOURCES]
        if args.templates_extra:
            cmd[4:4] = ["-I", os.path.abspath(args.templates_extra)]

        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit("probe failed to compile:\n" + r.stderr)

        out = subprocess.run([binary], capture_output=True, text=True)
        if out.returncode != 0:
            sys.exit("probe failed to run:\n" + out.stderr)

    lines = [l for l in out.stdout.splitlines() if l.strip()]
    if len(lines) != 280:
        sys.exit("expected 280 graph rows, got %d" % len(lines))

    with open(args.out, "w") as f:
        f.write(HEADER)
        f.write("\n".join(lines))
        f.write("\n")
    print("wrote %s (%d reference graphs)" % (args.out, len(lines)))


if __name__ == "__main__":
    main()
